const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")

const root = path.resolve(__dirname, "..")
const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"))
const bar = fs.readFileSync(path.join(root, "BarWidget.qml"), "utf8")
const panel = fs.readFileSync(path.join(root, "Panel.qml"), "utf8")
const helper = fs.readFileSync(path.join(root, "mouse-control"), "utf8")

test("manifest identifies the owned left-bar widget", () => {
  assert.equal(manifest.id, "io.github.ol4vr.mouse-control")
  assert.equal(manifest.version, "0.2.8")
  assert.equal(manifest.barWidget.defaultSection, "left")
  assert.deepEqual(manifest.kinds, ["bar-widget"])
})

test("bar presents the selected battery and strict charging indicator", () => {
  assert.match(bar, /activeDevice\.battery/)
  assert.doesNotMatch(bar, /var dpi|activeDevice\.dpi/)
  assert.match(bar, /leadingGap: Style\.spaceReal\(8\)/)
  assert.match(bar, /text: "󰍽"\s+color: button\.foreground/)
  assert.match(bar, /id: chargingIndicator/)
  assert.match(bar, /visible: Model\.chargingIndicatorVisible\(root\.activeDevice\)/)
  assert.match(helper, /charging=charging/)
  assert.match(bar, /text: ""\s+color: root\.successColor/)
  assert.match(bar, /font\.pixelSize: Style\.font\.iconSmall/)
  assert.match(bar, /spacing: Style\.space\(1\)/)
  assert.match(bar, /green\\s\*=\\s\*\["'\]\?/)
  assert.doesNotMatch(bar, /chargingIndicator[\s\S]{0,300}Color\.accent/)
  assert.match(bar, /color: root\.batteryWarning \? Color\.urgent : button\.foreground/)
  assert.match(bar, /batteryWarning: Model\.batteryWarning\(activeDevice, warningThreshold\)/)
  assert.match(bar, /source: Qt\.resolvedUrl\("Panel\.qml"\)/)
  assert.match(bar, /interval: 5000/)
})

test("popup offers manual device selection and explicit DPI presets", () => {
  assert.match(panel, /\["naga", "logitech"\]/)
  assert.match(panel, /\[600, 800, 1000, 1200, 1400, 1600\]/)
  assert.match(panel, /columns: 3/)
  assert.match(panel, /selected: root\.activeDevice && root\.activeDevice\.dpi === modelData/)
  assert.match(panel, /\["set-dpi", activeDevice\.id/)
  assert.doesNotMatch(panel, /\bRGB\b|lighting|button mapping/i)
})

test("popup presents the persisted warning threshold as compact status", () => {
  assert.match(panel, /LOW-BATTERY WARNING/)
  assert.match(panel, /You will be notified at or below/)
  assert.doesNotMatch(panel, /Notify once at or below/)
  assert.match(panel, /warningThreshold \+ "%"/)
  assert.doesNotMatch(panel, /\[15, 20, 25\]/)
  assert.doesNotMatch(panel, /Critical notification/)
})

test("popup keeps balanced content insets and a neutral selected-device heading", () => {
  assert.match(panel, /anchors\.leftMargin: Style\.space\(16\)/)
  assert.match(panel, /anchors\.rightMargin: Style\.space\(16\)/)
  assert.match(panel, /SELECTED DEVICE/)
  assert.match(panel, /id: selectedDeviceSection[\s\S]*text: "SELECTED DEVICE"/)
  assert.match(panel, /root\.activeDevice\.name : "Mouse unavailable"[\s\S]*color: root\.foreground/)
  assert.doesNotMatch(panel, /color: Qt\.rgba\(Color\.accent\.r/)
})

test("popup uses equal neutral metric cards and compact device status", () => {
  assert.match(panel, /foreground: selected \? Color\.accent/)
  assert.match(panel, /bordered: selected/)
  assert.match(panel, /id: dpiCard[\s\S]*width: \(deviceMetrics\.width - deviceMetrics\.spacing\) \/ 2/)
  assert.match(panel, /id: batteryCard[\s\S]*width: \(deviceMetrics\.width - deviceMetrics\.spacing\) \/ 2/)
  assert.match(panel, /id: batteryCard[\s\S]*height: dpiCard\.height[\s\S]*color: dpiCard\.color/)
  assert.match(panel, /id: selectedDpiValue[\s\S]*root\.activeDevice\.dpi[\s\S]*Style\.font\.display/)
  assert.match(panel, /id: selectedBatteryValue[\s\S]*root\.activeDevice\.battery[\s\S]*batteryWarning\(root\.activeDevice, root\.warningThreshold\)[\s\S]*\? Color\.urgent : root\.foreground/)
  assert.match(panel, /id: chargingStatus[\s\S]*root\.chargingText\(root\.activeDevice\)/)
  assert.match(panel, /id: connectionStatus[\s\S]*root\.connectionTypeText\(root\.activeDevice\)/)
  assert.match(panel, /id: deviceStatus\s+anchors\.horizontalCenter: parent\.horizontalCenter\s+spacing: Style\.space\(14\)/)
  assert.match(panel, /device\.charging === null\) return "Charging Unknown"/)
  assert.match(panel, /return device\.charging \? "Charging" : "Not Charging"/)
  assert.match(panel, /device\.connection === "hyperspeed"\) return "2\.4 GHz HyperSpeed"/)
  assert.match(panel, /device\.connection === "lightspeed"\) return "2\.4 GHz Lightspeed"/)
  assert.match(panel, /device\.connection === "usb" \|\| device\.connection === "wired"\) return "Wired"/)
  assert.match(panel, /text: "󰌘"[\s\S]*id: connectionStatus/)
  assert.doesNotMatch(panel, /Model\.connectionText\(root\.activeDevice\)/)
  assert.match(panel, /id: warningValue[\s\S]*color: root\.foreground/)
})

test("helper has no input monitor, RGB path, or mouse-disable operation", () => {
  assert.doesNotMatch(helper, /evdev|\/dev\/input|openrgb|set-led/i)
  assert.doesNotMatch(helper, /disable-device|device.*enabled/i)
  assert.match(helper, /ratbagctl/)
  assert.match(helper, /SetDpi/)
  assert.match(helper, /omarchy-notification-send/)
})
